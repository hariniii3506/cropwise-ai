@app.route("/recommend", methods=["GET", "POST"])
@login_required
def recommend():
    """Crop recommendation input form and Decision Tree inference engine."""
    user_id = session["user_id"]
    user = get_user_by_id(user_id)

    soil_types = ['Alluvial', 'Black', 'Clay', 'Laterite', 'Loamy', 'Red', 'Sandy']

    if request.method == "POST":
        soil_type = request.form.get("soil_type", "Loamy")
        ph = float(request.form.get("ph", 6.5))
        temperature = float(request.form.get("temperature", 25.0))
        humidity = float(request.form.get("humidity", 70.0))
        rainfall = float(request.form.get("rainfall", 1000.0))

        pred_crop = "Paddy"
        alt_crops = []

        if dt_model is not None and soil_encoder is not None and crop_encoder is not None:
            try:
                s_enc_input = "Clayey" if (soil_type == "Clay" and "Clayey" in soil_encoder.classes_ and "Clay" not in soil_encoder.classes_) else soil_type
                s_enc = soil_encoder.transform([s_enc_input])[0]
                input_df = pd.DataFrame([{
                    'Soil_Type_Encoded': s_enc,
                    'pH': ph,
                    'Temperature': temperature,
                    'Humidity': humidity,
                    'Rainfall': rainfall
                }])

                pred_idx = dt_model.predict(input_df)[0]
                pred_crop = crop_encoder.inverse_transform([pred_idx])[0]

                # Extract alternatives from probability distribution
                probs = dt_model.predict_proba(input_df)[0]
                top_indices = np.argsort(probs)[::-1]
                alt_crops = [
                    crop_encoder.classes_[i]
                    for i in top_indices
                    if probs[i] > 0 and crop_encoder.classes_[i] != pred_crop
                ][:3]
            except Exception as e:
                print(f"[WARN] Decision Tree inference exception: {e}")

        # Fallback alternatives if probability distribution yields fewer than 2
        if len(alt_crops) < 2:
            all_available = [c for c in crop_database.keys() if c != pred_crop]
            for candidate in all_available:
                c_info = crop_database.get(candidate, {})
                if soil_type in c_info.get("ideal_soil", []) or (soil_type == "Clay" and "Clayey" in c_info.get("ideal_soil", [])):
                    if candidate not in alt_crops:
                        alt_crops.append(candidate)
                if len(alt_crops) >= 3:
                    break
            if len(alt_crops) < 2:
                for fallback_crop in ["Wheat", "Maize", "Groundnut", "Banana"]:
                    if fallback_crop != pred_crop and fallback_crop not in alt_crops:
                        alt_crops.append(fallback_crop)
                    if len(alt_crops) >= 3:
                        break

        # Agronomic explainability reasoning
        crop_info = crop_database.get(pred_crop, {})
        ideal_ph = crop_info.get("ph_range", "6.0 - 7.5")
        ideal_temp = crop_info.get("temp_range", "20°C - 35°C")

        decision_notes = (
            f"Decision Tree Rule Branch: Soil type '{soil_type}', pH {ph:.1f} (Ideal: {ideal_ph}), "
            f"Temperature {temperature:.1f}°C (Ideal: {ideal_temp}), Humidity {humidity:.1f}%, "
            f"and Annual Rainfall {rainfall:.1f}mm align precisely with the optimal agronomic growth profile of {pred_crop}."
        )

        rec_id = save_recommendation(
            user_id=user_id,
            soil_type=soil_type,
            ph=ph,
            temperature=temperature,
            humidity=humidity,
            rainfall=rainfall,
            recommended_crop=pred_crop,
            alternative_crops=alt_crops,
            decision_notes=decision_notes,
            variety="Standard"
        )

        return redirect(url_for("result", rec_id=rec_id))

    return render_template(
        "recommend.html",
        soil_types=soil_types,
        current_user=user
    )

