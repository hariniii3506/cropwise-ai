@app.route("/alternatives")
def alternatives():
    """Alternative crops explorer based on primary crop suitability."""
    crop_name = request.args.get("crop", "Paddy").strip()
    if crop_name not in crop_database:
        crop_name = "Paddy"

    primary_crop = crop_database.get(crop_name)

    # Find secondary candidates
    alternatives_list = []
    for c_name, c_data in crop_database.items():
        if c_name != crop_name:
            # Match if they share ideal soil or similar temperature category
            if any(s in primary_crop.get("ideal_soil", []) for s in c_data.get("ideal_soil", [])):
                alternatives_list.append(c_data)
        if len(alternatives_list) >= 4:
            break

    if len(alternatives_list) < 3:
        for c_name, c_data in crop_database.items():
            if c_name != crop_name and c_data not in alternatives_list:
                alternatives_list.append(c_data)
            if len(alternatives_list) >= 3:
                break

    return render_template(
        "alternatives.html",
        primary_crop=primary_crop,
        alternatives=alternatives_list
    )

