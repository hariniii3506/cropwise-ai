def send_otp_email(recipient_email, otp_code, origin_url=None):
    """
    Sends the exact 6-digit OTP to the farmer's entered email using EmailJS REST API.
    Uses the exact EmailJS template variables:
      - email: recipient email address
      - passcode: exact 6-digit OTP generated by Flask
      - time: validity and timestamp information
    """
    now_str = datetime.datetime.now().strftime("%I:%M %p, %d %b %Y")
    time_str = f"5 minutes (Generated at {now_str})"

    payload = {
        "service_id": EMAILJS_SERVICE_ID,
        "template_id": EMAILJS_TEMPLATE_ID,
        "user_id": EMAILJS_PUBLIC_KEY,
        "template_params": {
            "email": recipient_email,
            "passcode": str(otp_code),
            "time": time_str
        }
    }

    if EMAILJS_PRIVATE_KEY and EMAILJS_PRIVATE_KEY.strip():
        payload["accessToken"] = EMAILJS_PRIVATE_KEY.strip()

    base_origin = (origin_url or "http://localhost:5000").rstrip("/")
    headers = {
        "Content-Type": "application/json",
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36",
        "Origin": base_origin,
        "Referer": f"{base_origin}/register"
    }

    try:
        req = urllib.request.Request(
            "https://api.emailjs.com/api/v1.0/email/send",
            data=json.dumps(payload).encode("utf-8"),
            headers=headers,
            method="POST"
        )
        with urllib.request.urlopen(req, timeout=12) as response:
            if response.status == 200:
                print(f"[OK] OTP {otp_code} successfully delivered to {recipient_email} via EmailJS.")
                return True, None
    except urllib.error.HTTPError as e:
        err_msg = e.read().decode("utf-8", errors="ignore")
        print(f"[ERROR] EmailJS HTTP Error {e.code} for {recipient_email}: {err_msg}")
        return False, f"Email delivery error ({e.code})"
    except Exception as e:
        print(f"[ERROR] EmailJS delivery error for {recipient_email}: {e}")
        return False, "Could not connect to email delivery service"
    return True, None

def check_smtp_connection():
    """Optional diagnostic helper to test SMTP reachability if requested via CLI."""
    smtp_server = os.environ.get("SMTP_SERVER", "smtp.gmail.com")
    smtp_port = int(os.environ.get("SMTP_PORT", 587))
    smtp_user = os.environ.get("SMTP_USERNAME") or os.environ.get("SENDER_EMAIL")
    smtp_pass = os.environ.get("SMTP_PASSWORD")
    if not smtp_user or not smtp_pass:
        print("[INFO] SMTP credentials not configured (EmailJS is used by default).")
        return True
    import smtplib
    try:
        server = smtplib.SMTP(smtp_server, smtp_port, timeout=10)
        server.starttls()
        server.login(smtp_user, smtp_pass)
        server.quit()
        print("[OK] SMTP connection verified.")
        return True
    except Exception as e:
        print(f"[ERROR] SMTP connection check failed: {e}")
        return False

