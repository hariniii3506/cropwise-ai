@app.route("/register", methods=["GET", "POST"])
def register():
    """Farmer registration initiation with 6-digit OTP dispatch."""
    if session.get("user_id"):
        return redirect(url_for("dashboard"))

    if request.method == "POST":
        name = request.form.get("name", "").strip()
        mobile = request.form.get("mobile", "").strip()
        email = request.form.get("email", "").strip().lower()
        farm_location = request.form.get("farm_location", "").strip()
        land_area = request.form.get("land_area", "1.0").strip()
        land_unit = request.form.get("land_unit", "Acres").strip()
        preferred_soil = request.form.get("preferred_soil", "Loamy").strip()
        password = request.form.get("password", "")
        confirm_password = request.form.get("confirm_password", "")

        if not name or not mobile or not email or not password:
            flash("Please fill in all required registration fields.", "danger")
            return render_template("register.html")

        if password != confirm_password:
            flash("Passwords do not match. Please re-enter your password.", "danger")
            return render_template("register.html")

        if len(password) < 6:
            flash("Password must be at least 6 characters in length.", "danger")
            return render_template("register.html")

        # Clean up any unverified duplicate user with the same email
        delete_unverified_user(email)

        # Create user record with is_verified = 0
        user_id, err = create_user(
            name=name,
            mobile=mobile,
            email=email,
            password=password,
            farm_location=farm_location,
            land_area=land_area,
            land_unit=land_unit,
            preferred_soil=preferred_soil,
            is_verified=0
        )

        if err:
            flash(err, "danger")
            return render_template("register.html")

        # Generate ONE 6-digit OTP (source of truth)
        otp_code = f"{random.randint(100000, 999999)}"
        otp_hash = generate_password_hash(otp_code)
        expiry = time.time() + 300  # 5 minutes validity

        update_user_otp(user_id, otp_hash, expiry, time.time())

        # Store pending session state for OTP screen
        session["pending_email"] = email
        session["pending_user_id"] = user_id
        session["pending_name"] = name
        session["otp_sent_at"] = time.time()

        # Send OTP via EmailJS
        origin_url = request.host_url
        email_sent, send_err = send_otp_email(email, otp_code, origin_url=origin_url)

        if not email_sent:
            flash("We couldn't send the verification OTP to your email. Please check your email address and try again.", "danger")
            return render_template("register.html")

        flash("A 6-digit verification OTP has been sent to your email. Please enter it to complete registration.", "success")
        return redirect(url_for("verify_otp"))

    return render_template("register.html")

@app.route("/verify-otp", methods=["GET", "POST"])
def verify_otp():
    """Verify the 6-digit OTP sent to the farmer's email."""
    if session.get("user_id"):
        return redirect(url_for("dashboard"))

    pending_email = session.get("pending_email")
    if not pending_email:
        flash("Registration session expired or not found. Please register again.", "warning")
        return redirect(url_for("register"))

    # Calculate resend countdown
    otp_sent_at = session.get("otp_sent_at", time.time())
    elapsed = int(time.time() - otp_sent_at)
    resend_in = max(0, 45 - elapsed)

    if request.method == "POST":
        entered_otp = request.form.get("otp", "").strip()

        if not entered_otp or len(entered_otp) != 6 or not entered_otp.isdigit():
            flash("Please enter the complete 6-digit OTP.", "danger")
            return render_template("verify_otp.html", resend_in=resend_in, email=pending_email)

        success, result = verify_user_otp(pending_email, entered_otp)

        if success:
            user_id = result
            user = get_user_by_id(user_id)
            if user:
                session["user_id"] = user["id"]
                session["user_name"] = user["name"]
                session["user_email"] = user["email"]

            # Clear temporary session data
            session.pop("pending_email", None)
            session.pop("pending_user_id", None)
            session.pop("pending_name", None)
            session.pop("otp_sent_at", None)

            flash("Email verified successfully! Welcome to CROPWISE AI.", "success")
            return redirect(url_for("dashboard"))
        else:
            if "expired" in str(result).lower():
                flash("Your OTP has expired. Please request a new OTP.", "danger")
            elif "too many" in str(result).lower():
                flash("Too many invalid attempts. Please request a new OTP.", "danger")
            else:
                flash("Incorrect OTP. Please try again.", "danger")
            return render_template("verify_otp.html", resend_in=resend_in, email=pending_email)

    return render_template("verify_otp.html", resend_in=resend_in, email=pending_email)

