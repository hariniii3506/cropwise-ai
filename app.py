@app.route("/schemes", methods=["GET", "POST"])
@login_required
def schemes():
    """Government Schemes discovery and customized eligibility engine."""
    user_id = session["user_id"]
    user = get_user_by_id(user_id)

    if not user:
        flash("User information not found.", "danger")
        return redirect(url_for("dashboard"))

    # Get latest recommended crop
    history = get_recommendation_history(user_id, limit=1)
    recommended_crop = None
    if history:
        recommended_crop = history[0].get("recommended_crop")

    # Defaults
    country = "India"
    state = "Tamil Nadu"
    district = ""
    land_area = str(user.get("land_area") or "1.0")
    farmer_category = "General"

    # Derive location from profile
    location = str(user.get("farm_location") or "").strip()
    if location:
        parts = [p.strip() for p in location.split(",") if p.strip()]
        if parts:
            district = parts[0]
        location_lower = location.lower()
        if "tamil" in location_lower or "nadu" in location_lower:
            state = "Tamil Nadu"

    # POST - update criteria
    if request.method == "POST":
        country = request.form.get("country", "").strip() or "India"
        state = request.form.get("state", "").strip() or "Tamil Nadu"
        district = request.form.get("district", "").strip()
        land_area = request.form.get("land_area", land_area).strip()
        farmer_category = request.form.get("farmer_category", "General").strip() or "General"

    # Query filters
    search_q = request.args.get("search", "").strip().lower()
    filter_category = request.args.get("category", "").strip()
    filter_eligibility = request.args.get("eligibility", "").strip().lower()

    CATEGORIES_ORDER = [
        "Crop-specific schemes/support",
        "General farmer assistance schemes",
        "Irrigation schemes",
        "Crop insurance",
        "Seeds/input assistance",
        "Farm equipment subsidies",
        "Soil/land improvement",
        "Organic/natural farming",
        "Other agriculture subsidies"
    ]

    grouped_schemes = {cat: [] for cat in CATEGORIES_ORDER}

    for scheme in GOVT_SCHEMES:
        status, reason = check_eligibility(
            scheme,
            country,
            state,
            district,
            recommended_crop,
            land_area,
            farmer_category
        )

        scheme_copy = scheme.copy()
        scheme_copy["status"] = status
        scheme_copy["eligibility_reason"] = reason

        # Search filter
        if search_q:
            searchable_text = " ".join([
                str(scheme.get("name") or "").lower(),
                str(scheme.get("purpose") or "").lower(),
                str(scheme.get("department") or "").lower(),
                str(scheme.get("category") or "").lower()
            ])
            if search_q not in searchable_text:
                continue

        # Category filter
        scheme_cat = str(scheme.get("category") or "").strip()
        if filter_category and scheme_cat != filter_category:
            continue

        # Eligibility filter
        if filter_eligibility:
            if filter_eligibility == "eligible" and status != "eligible":
                continue
            if filter_eligibility == "ineligible" and status != "ineligible":
                continue
            if filter_eligibility == "unconfirmed" and status != "unconfirmed":
                continue

        if scheme_cat in grouped_schemes:
            grouped_schemes[scheme_cat].append(scheme_copy)

    return render_template(
        "schemes.html",
        grouped_schemes=grouped_schemes,
        categories=CATEGORIES_ORDER,
        selected_category=filter_category,
        selected_eligibility=filter_eligibility,
        search_q=search_q,
        country=country,
        state=state,
        district=district,
        recommended_crop=recommended_crop,
        land_area=land_area,
        farmer_category=farmer_category
    )

